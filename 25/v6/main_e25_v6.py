# Пусть M – сумма минимального и максимального делителей целого числа, не считая единицы и самого числа.
# Если таких делителей у числа нет, то считаем значение M равным нулю. Напишите программу,
# которая перебирает целые числа, большие 1 000 000, в порядке возрастания и ищет среди них такие,
# для которых M оканчивается на 6. В ответе запишите в первом столбце таблицы первые пять найденных чисел
# в порядке возрастания, а во втором столбце – соответствующие им значения M.

def smallest_prime_factor(n):
   if n % 2 == 0:
       return 2
   i = 3
   while i * i <= n:
       if n % i == 0:
           return i
       i += 2
   return n  # n — простое

results = []
n = 1000001
while len(results) < 5:
   p = smallest_prime_factor(n)
   if p != n:  # составное
       M = p + n // p
       if M % 10 == 6:
           results.append((n, M))
   n += 1

for num, m in results:
   print(f"{num} {m}")