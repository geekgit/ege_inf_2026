# Пусть R – сумма различных натуральных делителей целого числа, не считая единицы и самого числа.
# Напишите программу, которая перебирает целые числа, бо́льшие 800 000, в порядке возрастания и ищет среди них такие,
# для которых R оканчивается на цифру 3. В ответ запишите в первом столбце таблицы первые пять найденных чисел
# в порядке возрастания, а во втором столбце – соответствующее значение R для каждого из них.
# Например, для числа 18 R = 2 + 3 + 6 + 9 = 20.
def sum(n):
   if n <= 1:
       return 0
   total = 0
   i = 2
   while i * i <= n:
       if n % i == 0:
           j = n // i
           if i == j:
               total += i
           else:
               total += i + j
       i += 1
   return total

results = []
n = 800001

while len(results) < 5:
   s = sum(n)
   if s % 10 == 3:
       results.append((n, s))
   n += 1

for n, s in results:
   print(f"{n} {s}")