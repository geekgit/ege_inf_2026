for i in range (0, 1001): # i будет в диапазоне от 0 до 1001, не включая 1001
    x = 1000 - i # x будет в диапазоне от 1000 до 0 включительно
    s = pow(6, 2025) + pow(6, 25) - x # s = 6^2025 + 6^25 - x
    cnt = 0
    while s > 0:
        if s % 6 == 0:
            cnt += 1
        s //= 6
    if cnt == 2002:
        print(x)
        break

