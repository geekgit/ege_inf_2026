for i in range (0, 801): # i будет в диапазоне от 0 до 801, не включая 801
    x = 800 - i # x будет в диапазоне от 800 до 0 включительно
    s = pow(7, 1040) + pow(7, 40) - x # s = 7^1010 + 7^40 - x
    cnt = 0
    while s > 0:
        if s % 7 == 0:
            cnt += 1
        s //= 7
    if cnt == 1002:
        print(x)
        break

