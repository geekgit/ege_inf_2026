for i in range (0, 3001): # i будет в диапазоне от 0 до 3001, не включая 3001
    x = 3000 - i # x будет в диапазоне от 3000 до 0 включительно
    s = 9 * pow(11, 210) + 8 * pow(11, 150) - x # s = 9*11^210 + 8*11^150 - x
    cnt = 0
    while s > 0:
        if s % 11 == 0:
            cnt += 1
        s //= 11
    if cnt == 60:
        print(x)
        break

