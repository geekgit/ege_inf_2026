for i in range (0, 2736): # i будет в диапазоне от 0 до 2736, не включая 2736
    x = 2735 - i # x будет в диапазоне от 2735 до 0 включительно
    s = pow(5, 2025) + pow(5, 1500) - x # s = 5^2025 + 5^1000 - x
    cnt = 0
    while s > 0:
        if s % 5 == 0:
            cnt += 1
        s //= 5
    if cnt == 527:
        print(x)
        break

